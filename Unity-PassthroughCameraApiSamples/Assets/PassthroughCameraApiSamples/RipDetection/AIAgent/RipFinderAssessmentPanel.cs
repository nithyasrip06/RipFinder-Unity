using System;
using TMPro;
using UnityEngine;
using UnityEngine.UI;

public sealed class RipFinderAssessmentPanel : MonoBehaviour
{
    [SerializeField]
    private RipFinderAgentClient agentClient;

    [SerializeField]
    private TMP_Text statusText;

    [SerializeField]
    private TMP_Text riskLevelText;

    [SerializeField]
    private TMP_Text riskScoreText;

    [SerializeField]
    private TMP_Text summaryText;

    [SerializeField]
    private TMP_Text recommendationText;

    [SerializeField]
    private TMP_Text safetyNoteText;

    private static readonly Color CardColor = new(0.07f, 0.08f, 0.10f, 0.88f);
    private static readonly Color MutedColor = new(0.56f, 0.59f, 0.64f, 1f);
    private static readonly Color TrackColor = new(1f, 1f, 1f, 0.10f);
    private static readonly Color NoteColor = new(1f, 1f, 1f, 0.05f);
    // Desaturated level accents; used for badge text/tint and the score bar.
    private static readonly Color LowColor = new(0.45f, 0.75f, 0.58f, 1f);
    private static readonly Color ModerateColor = new(0.88f, 0.70f, 0.42f, 1f);
    private static readonly Color HighColor = new(0.90f, 0.47f, 0.45f, 1f);
    private static readonly Color UnknownColor = new(0.55f, 0.60f, 0.66f, 1f);
    private const float BadgeTintAlpha = 0.16f;

    private RipFinderAssessmentResponse lastValidResponse;

    private Image badgeImage;
    private RectTransform scoreFill;
    private Image scoreFillImage;
    private GameObject summaryLabel;
    private GameObject recommendationLabel;
    private GameObject noteBox;

    private void Awake()
    {
        BuildLayout();
        ShowWaiting();
    }

    private void OnEnable()
    {
        if (agentClient == null)
        {
            Debug.LogError(
                "RipFinderAgentClient has not been assigned.");
            return;
        }

        agentClient.AssessmentReceived += ShowAssessment;
        agentClient.AssessmentFailed += ShowFailure;
    }

    private void OnDisable()
    {
        if (agentClient == null)
        {
            return;
        }

        agentClient.AssessmentReceived -= ShowAssessment;
        agentClient.AssessmentFailed -= ShowFailure;
    }

    private void ShowAssessment(
        RipFinderAssessmentResponse response)
    {
        lastValidResponse = response;

        string source = response.assessment_source == "claude"
            ? "AI: Claude"
            : "Rule engine";
        statusText.text = $"Updated {DateTime.Now:h:mm tt}  ·  {source}";

        SetRisk(
            response.risk_level,
            $"{response.risk_score:0.00}<size=55%><color=#8A929C>  / 1.00</color></size>",
            response.risk_score,
            LevelColor(response.risk_level));

        SetSections(
            response.summary,
            response.recommendation,
            response.safety_note);

        // Removable instrumentation: records whether the text now visible on the
        // panel was generated by Claude ("claude") or by the deterministic
        // fallback ("rule_engine_fallback"). Used to verify that a positive
        // screenshot really shows Claude output and not fallback wording.
        Debug.Log($"[RipFinder Assessment] source={response.assessment_source}");
    }

    private void ShowFailure(string error)
    {
        Debug.LogWarning(error);

        if (lastValidResponse != null)
        {
            statusText.text =
                "Refresh failed · showing last assessment";
            return;
        }

        statusText.text = "Service unreachable";
        SetRisk("N/A", "", 0f, UnknownColor);
        SetSections(
            "The assessment service could not be reached.",
            "Follow official beach warnings and lifeguards.",
            "");
    }

    private void ShowWaiting()
    {
        statusText.text = "Waiting for assessment...";
        SetRisk("--", "", 0f, UnknownColor);
        SetSections("", "", "");
    }

    private void SetRisk(string level, string score, float fill, Color color)
    {
        riskLevelText.text = level;
        riskLevelText.color = color;
        riskScoreText.text = score;
        badgeImage.color = new Color(color.r, color.g, color.b, BadgeTintAlpha);
        scoreFillImage.color = color;
        scoreFill.anchorMax = new Vector2(Mathf.Clamp01(fill), 1f);
    }

    private void SetSections(string summary, string recommendation, string safetyNote)
    {
        summaryText.text = summary;
        recommendationText.text = recommendation;
        safetyNoteText.text = safetyNote;

        summaryLabel.SetActive(!string.IsNullOrEmpty(summary));
        summaryText.gameObject.SetActive(!string.IsNullOrEmpty(summary));
        recommendationLabel.SetActive(!string.IsNullOrEmpty(recommendation));
        recommendationText.gameObject.SetActive(!string.IsNullOrEmpty(recommendation));
        noteBox.SetActive(!string.IsNullOrEmpty(safetyNote));
    }

    private static Color LevelColor(string level) => level switch
    {
        "HIGH" => HighColor,
        "MODERATE" => ModerateColor,
        "LOW" => LowColor,
        _ => UnknownColor,
    };

    #region Layout
    // Rearranges the prefab's text fields into a card:
    // header + status, level badge + score, score bar, labelled sections,
    // and a boxed safety note. The card grows to fit its content.
    private void BuildLayout()
    {
        var root = (RectTransform)transform;

        var background = GetComponent<Image>();
        Sprite rounded = background != null ? background.sprite : null;
        if (background == null) background = gameObject.AddComponent<Image>();
        background.color = CardColor;

        var layout = gameObject.AddComponent<VerticalLayoutGroup>();
        layout.padding = new RectOffset(26, 26, 20, 22);
        layout.spacing = 10f;
        layout.childControlWidth = true;
        layout.childControlHeight = true;
        layout.childForceExpandWidth = true;
        layout.childForceExpandHeight = false;

        var fitter = gameObject.AddComponent<ContentSizeFitter>();
        fitter.verticalFit = ContentSizeFitter.FitMode.PreferredSize;

        // Header: title on the left, status on the right.
        var header = CreateRow(root, "Header", 0f);
        var title = CreateText(header, "RIP CURRENT RISK", 15f, MutedColor, FontStyles.Bold);
        title.characterSpacing = 8f;
        title.gameObject.AddComponent<LayoutElement>().flexibleWidth = 1f;
        Adopt(statusText, header, 14f, MutedColor, FontStyles.Normal, TextAlignmentOptions.Right);

        // Level badge and score.
        var levelRow = CreateRow(root, "LevelRow", 18f);
        levelRow.GetComponent<HorizontalLayoutGroup>().childAlignment = TextAnchor.MiddleLeft;

        var badge = new GameObject("LevelBadge", typeof(RectTransform));
        badge.transform.SetParent(levelRow, false);
        badgeImage = badge.AddComponent<Image>();
        badgeImage.sprite = rounded;
        badgeImage.type = Image.Type.Sliced;
        var badgeLayout = badge.AddComponent<HorizontalLayoutGroup>();
        badgeLayout.padding = new RectOffset(16, 16, 4, 4);
        badgeLayout.childControlWidth = true;
        badgeLayout.childControlHeight = true;
        badge.AddComponent<LayoutElement>().flexibleWidth = 0f;
        Adopt(riskLevelText, (RectTransform)badge.transform, 20f, Color.white, FontStyles.Bold, TextAlignmentOptions.Center);
        riskLevelText.characterSpacing = 6f;

        Adopt(riskScoreText, levelRow, 30f, Color.white, FontStyles.Normal, TextAlignmentOptions.Right);
        riskScoreText.gameObject.AddComponent<LayoutElement>().flexibleWidth = 1f;

        // Score bar.
        var track = new GameObject("ScoreBar", typeof(RectTransform));
        track.transform.SetParent(root, false);
        var trackImage = track.AddComponent<Image>();
        trackImage.sprite = rounded;
        trackImage.type = Image.Type.Sliced;
        trackImage.color = TrackColor;
        track.AddComponent<LayoutElement>().preferredHeight = 4f;

        var fill = new GameObject("Fill", typeof(RectTransform));
        fill.transform.SetParent(track.transform, false);
        scoreFill = (RectTransform)fill.transform;
        scoreFill.anchorMin = Vector2.zero;
        scoreFill.anchorMax = new Vector2(0f, 1f);
        scoreFill.offsetMin = Vector2.zero;
        scoreFill.offsetMax = Vector2.zero;
        scoreFillImage = fill.AddComponent<Image>();
        scoreFillImage.sprite = rounded;
        scoreFillImage.type = Image.Type.Sliced;

        CreateSpacer(root, 4f);

        // Sections.
        summaryLabel = CreateSectionLabel(root, "SUMMARY");
        Adopt(summaryText, root, 18f, new Color(0.86f, 0.88f, 0.91f, 1f), FontStyles.Normal, TextAlignmentOptions.TopLeft);

        recommendationLabel = CreateSectionLabel(root, "WHAT TO DO");
        Adopt(recommendationText, root, 19f, Color.white, FontStyles.Normal, TextAlignmentOptions.TopLeft);

        // Safety note in a subtle box.
        noteBox = new GameObject("SafetyNoteBox", typeof(RectTransform));
        noteBox.transform.SetParent(root, false);
        var noteImage = noteBox.AddComponent<Image>();
        noteImage.sprite = rounded;
        noteImage.type = Image.Type.Sliced;
        noteImage.color = NoteColor;
        var noteLayout = noteBox.AddComponent<VerticalLayoutGroup>();
        noteLayout.padding = new RectOffset(14, 14, 10, 10);
        noteLayout.childControlWidth = true;
        noteLayout.childControlHeight = true;
        noteLayout.childForceExpandHeight = false;
        Adopt(safetyNoteText, (RectTransform)noteBox.transform, 14f, MutedColor, FontStyles.Normal, TextAlignmentOptions.TopLeft);
    }

    private static RectTransform CreateRow(RectTransform parent, string name, float spacing)
    {
        var go = new GameObject(name, typeof(RectTransform));
        go.transform.SetParent(parent, false);
        var row = go.AddComponent<HorizontalLayoutGroup>();
        row.spacing = spacing;
        row.childControlWidth = true;
        row.childControlHeight = true;
        row.childForceExpandWidth = false;
        row.childForceExpandHeight = false;
        return (RectTransform)go.transform;
    }

    private static void CreateSpacer(RectTransform parent, float height)
    {
        var go = new GameObject("Spacer", typeof(RectTransform));
        go.transform.SetParent(parent, false);
        go.AddComponent<LayoutElement>().preferredHeight = height;
    }

    private GameObject CreateSectionLabel(RectTransform parent, string label)
    {
        var text = CreateText(parent, label, 13f, MutedColor, FontStyles.Bold);
        text.characterSpacing = 6f;
        return text.gameObject;
    }

    private TMP_Text CreateText(RectTransform parent, string value, float size, Color color, FontStyles style)
    {
        var go = new GameObject(value, typeof(RectTransform));
        go.transform.SetParent(parent, false);
        var text = go.AddComponent<TextMeshProUGUI>();
        text.font = summaryText.font;
        text.text = value;
        Style(text, size, color, style, TextAlignmentOptions.Left);
        return text;
    }

    // Moves an existing prefab text into the card layout and restyles it.
    private static void Adopt(TMP_Text text, RectTransform parent, float size, Color color, FontStyles style, TextAlignmentOptions alignment)
    {
        text.transform.SetParent(parent, false);
        // Prefab texts are already children of the card root, so SetParent
        // alone keeps their old order; move them to the end explicitly.
        text.transform.SetAsLastSibling();
        Style(text, size, color, style, alignment);
    }

    private static void Style(TMP_Text text, float size, Color color, FontStyles style, TextAlignmentOptions alignment)
    {
        text.enableAutoSizing = false;
        text.fontSize = size;
        text.color = color;
        text.fontStyle = style;
        text.alignment = alignment;
        text.textWrappingMode = TextWrappingModes.Normal;
        text.overflowMode = TextOverflowModes.Overflow;
        text.raycastTarget = false;
    }
    #endregion
}
